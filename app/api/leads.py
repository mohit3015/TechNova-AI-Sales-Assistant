from typing import List, Optional
from fastapi import APIRouter, Depends, HTTPException, Query
from pydantic import BaseModel, EmailStr
from sqlalchemy.orm import Session

from app.database.connection import get_db
from app.database import crud


router = APIRouter(prefix="/leads", tags=["Leads"])


class LeadCreate(BaseModel):
    session_id: Optional[str] = None
    customer_name: Optional[str] = None
    email: Optional[str] = None
    phone: Optional[str] = None
    budget_max: Optional[int] = None
    preferred_ram: Optional[int] = None
    purpose: Optional[str] = None
    interested_product_id: Optional[str] = None
    lead_status: Optional[str] = "qualified"
    notes: Optional[str] = None


class LeadResponse(LeadCreate):
    id: int
    created_at: Optional[str] = None

    class Config:
        from_attributes = True


@router.post("", response_model=LeadResponse, status_code=201)
def capture_lead(lead_in: LeadCreate, db: Session = Depends(get_db)):
    """Save qualified sales lead generated by the AI sales assistant."""
    if not (lead_in.email or lead_in.phone or lead_in.session_id):
        raise HTTPException(status_code=400, detail="At least one of email, phone, or session_id is required.")

    lead = crud.create_lead(db, lead_in.model_dump())
    return lead.to_dict()


@router.get("", response_model=List[LeadResponse])
def get_captured_leads(
    limit: int = Query(20, ge=1, le=100),
    db: Session = Depends(get_db)
):
    """List captured customer leads for sales follow-up."""
    leads = crud.get_leads(db=db, limit=limit)
    return [l.to_dict() for l in leads]
